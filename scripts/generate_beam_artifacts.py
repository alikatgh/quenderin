#!/usr/bin/env python3
"""Emit pinned Beam shard records for the actual three-platform installers; no network."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def parts():
    manifest = json.loads((ROOT / 'shared/beam-artifacts.json').read_text())
    assert manifest['complete'] and manifest['shardCount'] == 4
    assert manifest['minimumMemoryBytes'] == 160 * 1024 ** 3
    result = []
    for index, source in enumerate(manifest['artifacts'], 1):
        part = dict(source)
        part['filename'] = Path(source['filename']).name
        assert part['filename'] == f'Beam-1.0-501B-A23B-UD-IQ2_XXS-{index:05d}-of-00004.gguf'
        assert part['url'] == f'https://huggingface.co/{manifest["repository"]}/resolve/{manifest["revision"]}/{source["filename"]}'
        assert re.fullmatch('[0-9a-f]{64}', part['sha256'])
        result.append(part)
    assert sum(p['downloadBytes'] for p in result) == 133885310500
    return result


def outputs():
    records = parts()
    note = '// Generated by scripts/generate_beam_artifacts.py; edit shared/beam-artifacts.json.\n'
    swift = note + 'enum BeamModelArtifacts {\n    static let parts: [ModelArtifact] = [\n'
    kotlin = 'package ai.quenderin.core\n\n' + note + 'internal object BeamModelArtifacts {\n    val parts: List<ModelArtifact> = listOf(\n'
    for p in records:
        values = [json.dumps(p[k]) for k in ('filename', 'url', 'sha256')]
        swift += '        .init(filename: ' + values[0] + ', url: ' + values[1] + ', sha256: ' + values[2] + ', downloadBytes: ' + str(p['downloadBytes']) + '),\n'
        kotlin += '        ModelArtifact(' + ', '.join(values) + ', ' + str(p['downloadBytes']) + 'L),\n'
    return {
        ROOT / 'src/beamModelArtifacts.ts': note + 'export const BEAM_ARTIFACTS = ' + json.dumps(records, indent=4) + ' as const;\n',
        ROOT / 'apple/QuenderinKit/Sources/QuenderinKit/BeamModelArtifacts.swift': swift + '    ]\n}\n',
        ROOT / 'android/quenderin-core/src/main/kotlin/ai/quenderin/core/BeamModelArtifacts.kt': kotlin + '    )\n}\n',
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, value in outputs().items():
        if args.check:
            assert path.read_text() == value, f'Stale Beam artifacts: {path}'
        else:
            path.write_text(value)
    print('Beam: all four pinned shard records in sync')
