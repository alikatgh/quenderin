#!/usr/bin/env python3
"""Generate the same pinned image-pair descriptors for all three clients."""
from pathlib import Path
import argparse
import json
ROOT = Path(__file__).resolve().parent.parent

def outputs():
    data = json.loads((ROOT / 'shared/vision-models.json').read_text())
    models = data['models']
    ts = '// Generated by scripts/generate_vision_models.py.\nexport const VISION_MODELS = ' + json.dumps(models, indent=2) + ' as const;\nexport type VisionModel = typeof VISION_MODELS[number];\nexport const visionModel = (id: string): VisionModel | undefined => VISION_MODELS.find(model => model.id === id);\n'
    header = '#pragma once\n#include <cstdint>\nstruct qv_artifact { const char * filename; uint64_t bytes; const char * sha256; };\nstruct qv_model_descriptor { const char * id; const char * family; qv_artifact model; qv_artifact projector; };\nstatic const qv_model_descriptor qv_models[] = {\n'
    swift = '// Generated by scripts/generate_vision_models.py.\nimport Foundation\npublic struct VisionArtifact: Sendable {\n    public let role: String\n    public let filename: String\n    public let bytes: Int64\n    public let sha256: String\n    public let url: URL\n}\npublic struct VisionModelDescriptor: Sendable {\n    public let id: String\n    public let label: String\n    public let minimumMemoryBytes: Int64\n    public let artifacts: [VisionArtifact]\n}\npublic enum VisionModels {\n    public static let all: [VisionModelDescriptor] = [\n'
    kt = '// Generated by scripts/generate_vision_models.py.\npackage ai.quenderin.core\n\ndata class VisionArtifact(val role: String, val filename: String, val bytes: Long, val sha256: String, val url: String)\ndata class VisionModelDescriptor(val id: String, val label: String, val minimumMemoryBytes: Long, val artifacts: List<VisionArtifact>)\nobject VisionModels {\n    val all: List<VisionModelDescriptor> = listOf(\n'
    q = json.dumps
    for m in models:
        a = m['artifacts']
        header += '    {' + q(m['id']) + ', ' + q(m['family']) + ', ' + ', '.join('{' + q(x['filename']) + f", {x['bytes']}ULL, " + q(x['sha256']) + '}' for x in a) + '},\n'
        swift += '        VisionModelDescriptor(id: ' + q(m['id']) + ', label: ' + q(m['label']) + f", minimumMemoryBytes: {m['minimumMemoryBytes']}, artifacts: [\n"
        kt += '        VisionModelDescriptor(' + q(m['id']) + ', ' + q(m['label']) + f", {m['minimumMemoryBytes']}L, listOf(\n"
        for x in a:
            swift += '            VisionArtifact(role: ' + q(x['role']) + ', filename: ' + q(x['filename']) + f", bytes: {x['bytes']}, sha256: " + q(x['sha256']) + ', url: URL(string: ' + q(x['url']) + ')!),\n'
            kt += '            VisionArtifact(' + q(x['role']) + ', ' + q(x['filename']) + f", {x['bytes']}L, " + q(x['sha256']) + ', ' + q(x['url']) + '),\n'
        swift += '        ]),\n'; kt += '        )),\n'
    swift += '    ]\n    public static func model(_ id: String) -> VisionModelDescriptor? { all.first { $0.id == id } }\n}\n'
    kt += '    )\n    fun model(id: String): VisionModelDescriptor? = all.firstOrNull { it.id == id }\n}\n'
    header += '};\n'
    return {'src/visionModels.ts': ts, 'native/vision/vision_models.generated.h': header, 'apple/QuenderinKit/Sources/QuenderinKit/VisionModels.swift': swift, 'android/quenderin-core/src/main/kotlin/ai/quenderin/core/VisionModels.kt': kt}

def main():
    p = argparse.ArgumentParser(); p.add_argument('--check', action='store_true'); args = p.parse_args()
    for name, value in outputs().items():
        target = ROOT / name
        if args.check:
            if not target.is_file() or target.read_text() != value:
                raise SystemExit('Vision descriptors stale: ' + name)
        else: target.write_text(value)
if __name__ == '__main__': main()
