#!/usr/bin/env python3
"""Invalidate local speed observations when their inference implementation changes."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
SWIFT = Path("apple/QuenderinKit/Sources/QuenderinKit/InferencePerformanceRuntime.swift")
KOTLIN = Path("android/quenderin-core/src/main/kotlin/ai/quenderin/core/InferencePerformanceRuntime.kt")


def source_paths(root: Path) -> list[Path]:
    paths = [Path("shared/prism-runtime.json"), Path("shared/inference-performance-contract.json"),
             Path("apple/QuenderinKit/Sources/QuenderinKit/InferenceEngine.swift"),
             Path("apple/QuenderinKit/Sources/QuenderinKit/LlamaEngine.swift"),
             Path("android/quenderin-core/src/main/kotlin/ai/quenderin/core/InferenceEngine.kt"),
             Path("android/quenderin-core/src/main/kotlin/ai/quenderin/core/LlamaEngine.kt"),
             Path("android/jni/CMakeLists.txt"), Path("android/jni/llama_jni.cpp")]
    paths.extend(path.relative_to(root) for path in (root / "android/jni").glob("*.h"))
    return sorted(set(paths), key=lambda path: path.as_posix())


def fingerprint(root: Path) -> str:
    digest = hashlib.sha256(b"quenderin-inference-performance-v1\0")
    for relative in source_paths(root):
        data = (root / relative).read_bytes()
        digest.update(relative.as_posix().encode("utf-8") + b"\0")
        digest.update(len(data).to_bytes(8, "big"))
        digest.update(data)
    return digest.hexdigest()


def outputs(identity: str) -> dict[Path, str]:
    return {
        SWIFT: '// Generated by scripts/generate_inference_performance_identity.py.\n'
               '// Cache identity only; compiled runtime capability remains authoritative.\n'
               'public enum InferencePerformanceRuntime {\n'
               f'    public static let id = "{identity}"\n' + '}\n',
        KOTLIN: '// Generated by scripts/generate_inference_performance_identity.py.\n'
                '// Cache identity only; compiled runtime capability remains authoritative.\n'
                'package ai.quenderin.core\n\nobject InferencePerformanceRuntime {\n'
                f'    const val ID = "{identity}"\n' + '}\n',
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    expected = outputs(fingerprint(ROOT))
    if args.check:
        if any(not (ROOT / path).is_file() or (ROOT / path).read_text() != text for path, text in expected.items()):
            print("Inference performance identity is stale; run the generator.", file=sys.stderr)
            return 1
        print("Inference performance identity matches its runtime and source inputs.")
    else:
        for path, text in expected.items():
            (ROOT / path).write_text(text)
        print("Generated Swift/Kotlin inference performance identity.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
