#!/usr/bin/env python3
"""Generate immutable Muse shard metadata for the three source catalogs. No network I/O."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def outputs():
    data = json.loads((ROOT / "shared/muse-spark-artifacts.json").read_text())
    parts = data["artifacts"]
    assert data["version"] == 1 and len(parts) == 22
    assert re.fullmatch(r"[0-9a-f]{40}", data["revision"])
    assert len({p["filename"].lower() for p in parts}) == len(parts)
    for index, part in enumerate(parts, 1):
        assert part["filename"] == f"Muse-Spark-Open-816B-A42B-Q2_K-{index:05d}-of-00022.gguf"
        assert part["url"] == f'https://huggingface.co/{data["repository"]}/resolve/{data["revision"]}/{part["filename"]}'
        assert re.fullmatch(r"[0-9a-f]{64}", part["sha256"])
        assert type(part["downloadBytes"]) is int and part["downloadBytes"] > 0
    assert sum(p["downloadBytes"] for p in parts) == 304080474208
    note = "// Generated by scripts/generate_muse_artifacts.py; edit the shared manifest.\n"
    ts = note + "export const MUSE_SPARK_ARTIFACTS = " + json.dumps(parts, indent=4) + " as const;\n"
    swift = note + "enum MuseModelArtifacts {\n    static let parts: [ModelArtifact] = [\n"
    kotlin = "package ai.quenderin.core\n\n" + note + "internal object MuseModelArtifacts {\n    val parts: List<ModelArtifact> = listOf(\n"
    for part in parts:
        values = [json.dumps(part[k]) for k in ["filename", "url", "sha256"]]
        swift += "        .init(filename: " + values[0] + ", url: " + values[1] + ", sha256: " + values[2] + ", downloadBytes: " + str(part["downloadBytes"]) + "),\n"
        kotlin += "        ModelArtifact(" + ", ".join(values) + ", " + str(part["downloadBytes"]) + "L),\n"
    swift += "    ]\n}\n"
    kotlin += "    )\n}\n"
    return {
        ROOT / "src/museModelArtifacts.ts": ts,
        ROOT / "apple/QuenderinKit/Sources/QuenderinKit/MuseModelArtifacts.swift": swift,
        ROOT / "android/quenderin-core/src/main/kotlin/ai/quenderin/core/MuseModelArtifacts.kt": kotlin,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != expected:
                raise SystemExit(f"Stale Muse metadata: {path.relative_to(ROOT)}")
        else:
            path.write_text(expected)
    print("Muse metadata: 22 verified records, three catalogs in sync")


if __name__ == "__main__":
    main()
